// Sorted dictionary keys by descending length for greedy multi-word replacement
const sortedKeys = Object.keys(DICTIONARY).sort((a, b) => b.length - a.length);

/**
 * Helper to translate a string segment using exact match or greedy phrase replacement
 */
export const translateString = (text: string, langCode: string): string => {
  if (!text || langCode === 'en') return text;
  const trimmed = text.trim();
  if (!trimmed) return text;

  // 1. Exact match (fast path)
  if (DICTIONARY[trimmed] && DICTIONARY[trimmed][langCode]) {
    return text.replace(trimmed, DICTIONARY[trimmed][langCode]);
  }

  // 2. Greedy phrase replacement inside longer texts
  let result = text;
  let changed = false;

  for (const phrase of sortedKeys) {
    if (result.includes(phrase)) {
      const translation = DICTIONARY[phrase][langCode];
      if (translation) {
        result = result.split(phrase).join(translation);
        changed = true;
      }
    }
  }

  return changed ? result : text;
};

// Caches for node originals to avoid memory leaks
const originalTextMap = new WeakMap<Node, string>();
const originalPlaceholderMap = new WeakMap<Element, string>();
const originalOptionTextMap = new WeakMap<HTMLOptionElement, string>();

let isTranslating = false;

/**
 * Traverses DOM and translates all text nodes, options, inputs, and placeholders into target language.
 * Never modifies layout, direction, styles, classes, or formatting!
 */
export const applyDomTranslation = (langCode: string): void => {
  if (typeof window === 'undefined' || isTranslating) return;

  const root = document.getElementById('root');
  if (!root) return;

  isTranslating = true;
  try {
    // 1. Walk Text Nodes
    const walker = document.createTreeWalker(
      root,
      NodeFilter.SHOW_TEXT,
      {
        acceptNode: (node) => {
          if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
          const parent = node.parentElement;
          if (!parent) return NodeFilter.FILTER_REJECT;
          const tagName = parent.tagName.toLowerCase();
          if (tagName === 'script' || tagName === 'style' || tagName === 'noscript' || tagName === 'code') {
            return NodeFilter.FILTER_REJECT;
          }
          return NodeFilter.FILTER_ACCEPT;
        }
      }
    );

    const textNodesToUpdate: { node: Node; text: string }[] = [];
    let currentNode = walker.nextNode();

    while (currentNode) {
      let orig = originalTextMap.get(currentNode);
      if (orig === undefined) {
        orig = currentNode.nodeValue || '';
        originalTextMap.set(currentNode, orig);
      }

      if (langCode === 'en') {
        if (currentNode.nodeValue !== orig) {
          textNodesToUpdate.push({ node: currentNode, text: orig });
        }
      } else {
        const translated = translateString(orig, langCode);
        if (translated !== currentNode.nodeValue) {
          textNodesToUpdate.push({ node: currentNode, text: translated });
        }
      }

      currentNode = walker.nextNode();
    }

    for (const item of textNodesToUpdate) {
      item.node.nodeValue = item.text;
    }

    // 2. Translate Input and Textarea Placeholders
    const inputs = root.querySelectorAll<HTMLInputElement | HTMLTextAreaElement>('input, textarea');
    inputs.forEach((input) => {
      let origPlaceholder = originalPlaceholderMap.get(input);
      if (origPlaceholder === undefined) {
        origPlaceholder = input.getAttribute('placeholder') || '';
        originalPlaceholderMap.set(input, origPlaceholder);
      }

      if (!origPlaceholder) return;

      if (langCode === 'en') {
        if (input.getAttribute('placeholder') !== origPlaceholder) {
          input.setAttribute('placeholder', origPlaceholder);
        }
      } else {
        const translated = translateString(origPlaceholder, langCode);
        if (input.getAttribute('placeholder') !== translated) {
          input.setAttribute('placeholder', translated);
        }
      }
    });

    // 3. Translate Select Options
    const options = root.querySelectorAll<HTMLOptionElement>('option');
    options.forEach((opt) => {
      let orig = originalOptionTextMap.get(opt);
      if (orig === undefined) {
        orig = opt.textContent || '';
        originalOptionTextMap.set(opt, orig);
      }

      if (!orig) return;

      if (langCode === 'en') {
        if (opt.textContent !== orig) {
          opt.textContent = orig;
        }
      } else {
        const translated = translateString(orig, langCode);
        if (opt.textContent !== translated) {
          opt.textContent = translated;
        }
      }
    });
  } finally {
    isTranslating = false;
  }
};
