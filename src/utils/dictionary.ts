/**
 * Apply dictionary-based translation to text nodes across the DOM safely
 */
export const applyDomTranslation = (langCode: string): void => {
  if (typeof document === 'undefined' || !langCode || langCode === 'en') return;

  const dict = TRANSLATION_DICTIONARY[langCode];
  if (!dict) return;

  // Set RTL / LTR direction on root HTML if Arabic or Urdu
  const html = document.documentElement;
  if (langCode === 'ur' || langCode === 'ar') {
    html.setAttribute('dir', 'rtl');
    html.classList.add('rtl-layout');
  } else {
    html.setAttribute('dir', 'ltr');
    html.classList.remove('rtl-layout');
  }
};
